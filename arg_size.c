int	arg_size(char *num)
{
	int	count;
	int	i;

	count = 0;
	i = 0;
	while (num[i] != '\0')
	{
		if((num[i] >= 9 && num[i] <= 13) || num[i] == 32)
			i++;
		else
		{
			count++;
			while (num[i] != '\0' && !((num[i] >= 9 && num[i] <= 13) || num[i] == 32))
				i++;
		}
	}
	return (count);
}		
